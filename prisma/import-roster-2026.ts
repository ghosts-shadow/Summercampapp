const isNA = (s: string) =>
  !s || ["N/A", "NA", "DECEASED"].includes(s.trim().toUpperCase());

function splitName(full: string): { firstName: string; lastName: string } {
  const parts = full.trim().split(/\s+/);
  if (parts.length === 1) return { firstName: parts[0], lastName: parts[0] };
  return {
    firstName: parts.slice(0, -1).join(" "),
    lastName: parts[parts.length - 1],
  };
}

async function main() {
  let groupCount = 0;
  let camperCount = 0;

  for (const g of GROUPS) {
    const group = await prisma.group.upsert({
      where: { name: g.name },
      create: { name: g.name, color: g.color },
      update: { color: g.color },
    });
    groupCount++;

    for (const [extId, fullName, age, sex, allergies, fName, fPhone, mName, mPhone] of g.campers) {
      const { firstName, lastName } = splitName(fullName);

      // Guardian = father, unless his name is N/A/deceased — then mother.
      const fatherOk = !isNA(fName);
      const motherOk = !isNA(mName);
      const guardianName = fatherOk ? fName : motherOk ? mName : "Parent / Guardian";
      const guardianPhone = fatherOk ? fPhone : motherOk ? mPhone : fPhone;
      // Emergency contact = the other parent (name + phone), or the other phone.
      const emergencyContact = fatherOk
        ? `${motherOk ? mName + " " : ""}${mPhone}`.trim()
        : `${fPhone}`;

      const data = {
        firstName,
        lastName,
        age,
        gender: sex === "F" ? Gender.FEMALE : Gender.MALE,
        guardianName,
        guardianPhone,
        emergencyContact,
        medicalNotes: isNA(allergies) ? null : allergies,
        groupId: group.id,
      };

      await prisma.camper.upsert({
        where: { externalId: extId },
        create: { externalId: extId, ...data },
        update: data,
      });
      camperCount++;
    }
    console.log(`✅  ${g.name} — ${g.campers.length} campers`);
  }

  console.log(`\nDone: ${groupCount} groups, ${camperCount} campers imported.`);
  console.log(`DB totals: groups=${await prisma.group.count()}, campers=${await prisma.camper.count()}`);
}

main()
  .catch((e) => {
    console.error(e);
    process.exit(1);
  })
  .finally(() => prisma.$disconnect());
